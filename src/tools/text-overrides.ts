/**
 * Переопределение текста инструментов из админки.
 *
 * ЧТО ЗДЕСЬ ПРОИСХОДИТ. Описание инструмента — единственный текст, по которому
 * модель решает, чем воспользоваться. Заказчик правит его из админки, правка
 * приезжает сюда каталогом и накладывается на определения из кода.
 *
 * ПРАВИЛО — НЕ «ДВА ПОЛЯ», А «НИ ОДНОГО ПОЛЯ, МЕНЯЮЩЕГО ПРИРОДУ ИНСТРУМЕНТА».
 * Формулировка важна: арифметика приглашает однажды сказать «список ведь уже
 * расширяли, добавим ещё одно», а этот критерий — нет.
 *
 * Имя — исполняемый ключ трёх механизмов защиты, которые адресуют инструменты
 * ПО ИМЕНИ: `TOOLS_RETURNING_FOREIGN_TEXT` (забор вокруг текста респондентов),
 * `MUTATING_PREFIXES`/`READ_ONLY_TOOLS` (слепки отката),
 * `TOOLS_WITHHELD_FROM_CHAT` (четыре стирающих инструмента изъяты из чата).
 * Переименование из админки тихо снимает защиту. Схема — контракт между
 * моделью и обработчиком, проверить админскую схему против обработчика нечем.
 * Флаги — принуждение, а не документация. Сегодня под критерий подходят ровно
 * `description` и `title`; завтра, если появится третье поле такого же
 * свойства, критерий ответит за него сам.
 *
 * СИРОТА ИНЕРТЕН ПО ПОСТРОЕНИЮ. Каталог приезжает по именам, и имя, которого
 * в коде уже нет, просто ни на что не ложится — не потому, что кто-то не забыл
 * удалить строку, а потому, что накладывать её не на что.
 *
 * ИНВАРИАНТЫ ОСТАЮТСЯ ЗА КОДОМ. Факты, которые модель обязана знать про
 * инструмент независимо от того, что о нём написал администратор, живут в
 * `ToolDefinition.invariants` и дописываются {@link renderDescription} уже
 * ПОСЛЕ переопределённого текста. Забор вокруг инструкции убивает инструкцию,
 * поэтому это не фильтр враждебного текста, а гарантия, что правка не сотрёт
 * то, чего сама не знает.
 */

import type { ToolDefinition } from "./shared.js";

/** Что администратор может переопределить у одного инструмента. Закрытый список. */
export interface ToolTextOverride {
  title?: string;
  description?: string;
}

/** Переопределения по имени инструмента. Дельта, а не копия каталога. */
export type ToolTextCatalogue = Record<string, ToolTextOverride>;

/**
 * Пределы, дублирующие серверную проверку.
 *
 * Сервер — место, где правка ОТКЛОНЯЕТСЯ с внятным текстом; здесь — последний
 * рубеж на случай, если в базу что-то попало мимо валидатора. Поэтому реакция
 * разная: там 400, тут молчаливый откат к коду. Обрезать текст было бы хуже
 * всего — модель получила бы фразу, оборванную на половине условия.
 */
export const TOOL_TEXT_LIMITS = {
  title: 60,
  description: 1000,
  /** Общий бюджет каталога; сегодня весь набор описаний — около 6 700 символов. */
  total: 12_000,
} as const;

/**
 * ANSI-escape: CSI-последовательности и одиночные управляющие escape'ы.
 */
const ANSI = /\u001B\[[0-9;?]*[ -/]*[@-~]|\u001B[@-Z\\-_]/g;

/**
 * Нулевая ширина, мягкий перенос и знаки смены направления письма.
 *
 * Эти символы делают текст НЕ ТЕМ, ЧЕМ ОН ВЫГЛЯДИТ: строка в поле ввода
 * админки и строка, уехавшая модели, перестают совпадать, а ревью глазами
 * перестаёт что-либо значить. Ни одной осмысленной формулировке они не нужны.
 */
const INVISIBLE = /[\u00AD\u200B-\u200F\u202A-\u202E\u2060-\u2064\u2066-\u206F\uFEFF]/g;

/** Управляющие символы, кроме перевода строки. */
const CONTROL = /[\u0000-\u0009\u000B-\u001F\u007F]/g;

/** Больше двух переводов строки подряд — это вёрстка, а не абзацы. */
const EXTRA_BLANK_LINES = /\n{3,}/g;

/**
 * Привести текст к тому, чем он выглядит.
 *
 * ПОЧЕМУ ЗДЕСЬ, А НЕ ТОЛЬКО НА СЕРВЕРЕ. Это последний рубеж на пути в промпт
 * модели, и он обязан стоять независимо от того, КАК текст попал в базу.
 * Сервер отклоняет плохую правку с внятным текстом — но поддержка ходит в базу
 * руками, ради этого фича и делается, и запрос UPDATE мимо валидатора никого
 * не спросит. Отсюда же и разная реакция: там 400, тут молчаливая очистка.
 *
 * Ни одной осмысленной формулировки это не режет — оно вырубает класс правок,
 * которые в админке выглядят одним, а модели уезжают другим.
 */
export function sanitizeToolText(raw: string): string {
  return raw
    .normalize("NFC")
    .replace(ANSI, "")
    .replace(INVISIBLE, "")
    .replace(/\r\n?/g, "\n")
    .replace(CONTROL, "")
    .replace(EXTRA_BLANK_LINES, "\n\n")
    .trim();
}

/**
 * Годный ли это текст. `null` означает «бери из кода».
 *
 * Пустая строка — не значение: администратор, стёрший поле, просит вернуть
 * дефолт, а не оставить инструмент без описания. Длина считается ПОСЛЕ
 * очистки: предел про то, что уедет модели, а не про то, что лежит в базе.
 */
function usableText(value: unknown, limit: number): string | null {
  if (typeof value !== "string") return null;
  const clean = sanitizeToolText(value);
  if (clean.length === 0 || clean.length > limit) return null;
  return clean;
}

/**
 * Итоговый текст, который увидит модель.
 *
 * Собирается в одном месте на все три двери — иначе «что именно уехало
 * провайдеру» пришлось бы выяснять отдельно для чата, stdio и HTTP.
 *
 * @param tool определение из кода (или уже с наложенным переопределением)
 * @param override необязательное переопределение, если накладывать надо прямо здесь
 */
export function renderDescription(tool: ToolDefinition, override?: ToolTextOverride): string {
  const base = usableText(override?.description, TOOL_TEXT_LIMITS.description) ?? tool.description;
  const invariants = (tool.invariants ?? []).filter((line) => line.trim().length > 0);
  if (invariants.length === 0) return base;
  return `${base}\n\n${invariants.join(" ")}`;
}

/** Итоговый заголовок: переопределение, если годное, иначе из кода. */
export function renderTitle(tool: ToolDefinition, override?: ToolTextOverride): string {
  return usableText(override?.title, TOOL_TEXT_LIMITS.title) ?? tool.title;
}

/**
 * Наложить каталог на определения инструментов.
 *
 * Возвращает НОВЫЕ объекты, в которых отличаются ровно `title` и `description`;
 * всё остальное — имя, схема, флаги, обработчик, инварианты — переносится
 * ссылкой из исходного определения. На это свойство есть отдельный тест с
 * глубоким сравнением: он сторож против будущей правки «ну и флажок заодно».
 *
 * Описание в результате остаётся БАЗОВЫМ текстом, а не собранным: инварианты
 * дописывает {@link renderDescription} в момент доставки. Иначе повторное
 * наложение удваивало бы их.
 */
export function applyToolText<T extends ToolDefinition>(
  tools: readonly T[],
  catalogue?: ToolTextCatalogue | null,
): T[] {
  if (!catalogue) return [...tools];

  return tools.map((tool) => {
    const override = catalogue[tool.name];
    if (!override) return tool;

    const title = usableText(override.title, TOOL_TEXT_LIMITS.title);
    const description = usableText(override.description, TOOL_TEXT_LIMITS.description);
    if (title === null && description === null) return tool;

    return {
      ...tool,
      ...(title !== null ? { title } : {}),
      ...(description !== null ? { description } : {}),
    };
  });
}

/** Сколько символов каталог добавляет к промпту. Для проверки общего бюджета. */
export function catalogueSize(catalogue: ToolTextCatalogue): number {
  return Object.values(catalogue).reduce(
    (total, override) => total + (override.title?.length ?? 0) + (override.description?.length ?? 0),
    0,
  );
}
